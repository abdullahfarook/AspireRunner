namespace AspireRunner.Tool.Commands;

public class RunCommand : AsyncCommand<RunCommand.Settings>
{
    public class Settings : CommandSettings
    {
        [CommandArgument(0, "[version]")]
        [Description("The version of the dashboard to run")]
        public string? Version { get; set; }

        [CommandOption("-b|--browser")]
        [Description("Launch the dashboard in the default browser")]
        public bool LaunchBrowser { get; set; }

        [DefaultValue(18888)]
        [CommandOption("-p|--port")]
        [Description("The port the dashboard will be available on")]
        public int DashboardPort { get; init; }

        [CommandOption("-a|--auth")]
        [Description("Use browser token authentication for the dashboard")]
        public bool UseAuth { get; init; }

        [CommandOption("-t|--token")]
        [Description("The token to use for dashboard authentication, if not passed, the token will be randomly generated by the dashboard")]
        public string? AuthToken { get; set; }

        [DefaultValue(true)]
        [CommandOption("-s|--https")]
        [Description("Use HTTPS instead of HTTP, this applies to the dashboard, OTLP and MCP servers")]
        public bool? UseHttps { get; init; }

        [CommandOption("--dashboard-https")]
        [Description("Use HTTPS instead of HTTP for the dashboard, overrides the global HTTPS option")]
        public bool? DashboardHttps { get; init; }

        [DefaultValue(4317)]
        [CommandOption("--otlp-port")]
        [Description("The port the OTLP/gRPC server will listen on, can be disabled by passing 0")]
        public int OtlpPort { get; init; }

        [CommandOption("--otlp-http-port")]
        [Description("The port the OTLP/HTTP server will listen on, by default, only the gRPC server is started")]
        public int? OtlpHttpPort { get; set; }

        [CommandOption("--otlp-key")]
        [Description("The API key to use for the OTLP server")]
        public string? OtlpKey { get; set; }

        [CommandOption("--otlp-https")]
        [Description("Use HTTPS instead of HTTP for the OTLP/gRPC and OTLP/HTTP endpoints, overrides the global HTTPS option")]
        public bool? OtlpHttps { get; set; }

        [CommandOption("--cors-origins")]
        [Description("The allowed origins for CORS requests, separated by a comma. A wildcard (*) can be used to allow any domain")]
        public string? CorsAllowedOrigins { get; set; }

        [CommandOption("--cors-headers")]
        [Description("The allowed headers for CORS requests, separated by a comma")]
        public string? CorsAllowedHeaders { get; set; }

        [DefaultValue("localhost")]
        [CommandOption("--hostname")]
        [Description("The hostname used for the dashboard, OTLP and MCP servers")]
        public string? Hostname { get; set; }

        [DefaultValue(false)]
        [CommandOption("-m|--multiple")]
        [Description("Allow running multiple instances of the dashboard, if not passed, existing instances will be replaced")]
        public bool AllowMultipleInstances { get; set; }

        [DefaultValue(true)]
        [CommandOption("--auto-update")]
        [Description("Automatically update the dashboard to the latest version")]
        public bool? AutoUpdate { get; set; }

        [DefaultValue(18891)]
        [CommandOption("--mcp-port")]
        [Description("The port the MCP server will listen on, can be disabled by passing 0, disabling will remove MCP-related UI in the dashboard")]
        public int McpPort { get; set; }

        [CommandOption("--mcp-key")]
        [Description("The API key to use for the MCP server")]
        public string? McpKey { get; set; }

        [CommandOption("--mcp-https")]
        [Description("Use HTTPS instead of HTTP for the MCP server, overrides the global HTTPS option")]
        public bool? McpHttps { get; set; }

        [CommandOption("--verbose")]
        [Description("Enable verbose logging")]
        public bool? Verbose { get; set; }
    }

    private IDashboard? _dashboard;
    private bool _dashboardStarted;
    private LogRecord[] _currentLog = [];
    private int _currentWidth = AnsiConsole.Profile.Width;
    private int _currentHeight = AnsiConsole.Profile.Height;
    private readonly InMemoryProcessManager _processManager = InMemoryProcessManager.Instance;
    private string _inventoryState = string.Empty;
    private string? _dashboardProcessId;

    protected override async Task<int> ExecuteAsync(CommandContext context, Settings settings, CancellationToken cancellationToken)
    {
        Logger.Verbose = settings.Verbose ?? false;

        if (string.IsNullOrEmpty(DotnetCli.Path))
        {
            Widgets.Write(Widgets.Error("The dotnet CLI was not found, make sure it's installed and available in your PATH environment variable."));
            return -100;
        }

        // Prepare dashboard options
        var dashboardOptions = BuildOptions(settings);
        var otlpEndpoints = GetEnabledEndpoints(dashboardOptions);

        if (dashboardOptions.Runner.AutoUpdate)
        {
            var installer = new DashboardInstaller(Logger.DefaultFactory.CreateLogger<DashboardInstaller>());
            Widgets.Write("Checking for updates ");

            var result = await installer.EnsureLatestAsync(cancellationToken).ShowSpinner();
            Widgets.Write(Widgets.SuccessCheck(), true);

            if (result.Installed != result.Latest)
            {
                Widgets.Write([$"Dashboard updated to version {result.Latest} ".Widget(), Widgets.SuccessCheck()], true);
            }
        }

        using var sessionCts = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
        var sessionToken = sessionCts.Token;

        // Register runner signal handlers
        using var sigInt = PosixSignalRegistration.Create(PosixSignal.SIGINT, SignalHandler);
        using var sigTerm = PosixSignalRegistration.Create(PosixSignal.SIGTERM, SignalHandler);

        // Create and start the dashboard
        var processFactory = new ProcessFactory(Logger.DefaultFactory.CreateLogger<ProcessFactory>(), Logger.DefaultFactory);
        using var lpcServer = StartLpcServer(processFactory, () =>
        {
            sessionCts.Cancel();
            return Task.CompletedTask;
        });
        if (lpcServer is not null)
        {
            Widgets.WriteInterpolated($"LPC endpoint [{Widgets.PrimaryColorText}]127.0.0.1:{lpcServer.Port}[/] is available for ProcessManager.Client", true);
        }

        _dashboard = await processFactory.CreateAspireDashboardAsync(dashboardOptions);
        if (_dashboard is null)
        {
            Widgets.Write("No dashboards found. Installing the latest version...", true);
            var installationResult = await new InstallCommand().ExecuteFromRunCommandAsync(context, new() { Version = "latest" }, cancellationToken);
            if (installationResult is not 0)
            {
                return installationResult;
            }

            _dashboard = await processFactory.CreateAspireDashboardAsync(dashboardOptions);
            if (_dashboard is null)
            {
                Widgets.Write(Widgets.Error("Failed to create a dashboard instance after installation"));
                return -1;
            }
        }

        if (settings.Version is not null && !VersionRange.Parse(settings.Version, true).IsSatisfied(_dashboard.Version))
        {
            Widgets.Write(Widgets.Error($"No version matching '{settings.Version}' is installed, run '{RunnerInfo.CommandName} aspire install {settings.Version}' to install it"));
            return 2;
        }

        Widgets.WriteInterpolated($"Found dashboard version [{Widgets.PrimaryColorText}]{_dashboard.Version}[/] at {_dashboard.InstallationPath}", true);

        await _dashboard.StartAsync(sessionToken);
        _dashboardStarted = _dashboard.IsRunning;

        if (!_dashboardStarted)
        {
            var (dashboard, runner) = Dashboard.TryGetRunningInstance();
            if (dashboard.IsRunning() || runner.IsRunning())
            {
                Widgets.Write(Widgets.Error($"Another instance of the dashboard is already running{Environment.NewLine}Runner PID: [{Widgets.PrimaryColorText}]{runner?.Id}[/], Dashboard PID: [{Widgets.PrimaryColorText}]{dashboard?.Id}[/]"));
                return -2;
            }

            Widgets.Write(Widgets.Error("Failed to start the dashboard"));
            return -1;
        }

        SyncDashboardInventory();

        // Prepare a single interactive workspace with clearly separated boundaries:
        // left side = managed processes + selected process logs, right side = Aspire status + Aspire logs.
        var defaultStatus = Widgets.StatusSymbol(false);
        var table = new Table()
            .Collapse()
            .BorderStyle(new Style(Widgets.PrimaryColor, decoration: Decoration.Dim))
            .AddColumn("", c => c.Centered().Width(14).NoWrap())
            .AddColumn("Status", c => c.Centered().Width(12))
            .AddColumn("Port", c => c.Centered().Width(10))
            .AddColumn("Authentication", c => c.Centered().Width(30).NoWrap())
            .AddRow("Dashboard".Widget(), defaultStatus)
            .AddRow("OTLP/gRPC".Widget(), defaultStatus)
            .AddRow("OTLP/HTTP".Widget(), defaultStatus)
            .AddRow("MCP".Widget(), defaultStatus);

        var actions = new Columns(
            Widgets.KeyActionDescriptor("↑/↓", "Select process"),
            Widgets.KeyActionDescriptor("L", "Reload logs"),
            Widgets.KeyActionDescriptor("S", "Stop selected"),
            Widgets.KeyActionDescriptor("R", "Restart selected"),
            Widgets.KeyActionDescriptor("D", "Delete selected"),
            Widgets.KeyActionDescriptor("K", "Kill all + exit"),
            Widgets.KeyActionDescriptor("B", "Open browser"),
            Widgets.KeyActionDescriptor("H", "Help"),
            Widgets.KeyActionDescriptor("Esc/Ctrl+C", "Exit")
        ).Collapse().PadRight(3);

        var actionStatus = "Select a process, then use S/R/D actions. Logs panel includes history + live updates.";
        var selectedProcessId = string.Empty;
        var processLogEntries = new List<(string Stream, string Message)>();
        var processLogCursors = new Dictionary<string, (int StdoutCount, int StderrCount)>(StringComparer.OrdinalIgnoreCase);
        var processLogsProcessId = string.Empty;
        var reloadSelectedProcessLogs = true;
        var serviceStatusState = string.Empty;
        var selectedDetailsState = string.Empty;
        var killRequested = false;
        const int maxProcessLogLines = 300;

        var mainLayout = new Layout("main").SplitRows(
            new Layout("header", BuildHeader()).Ratio(1),
            new Layout("body").SplitColumns(
                new Layout("left").SplitRows(
                    new Layout("processes", BuildProcessPanel()).Ratio(7),
                    new Layout("process-logs", BuildProcessLogsPanel()).Ratio(8)
                ).Ratio(3),
                new Layout("right").SplitRows(
                    new Layout("aspire-status", BuildAspireStatusPanel()).Ratio(5),
                    new Layout("process-details", BuildProcessDetailsPanel()).Ratio(8)
                ).Ratio(2)
            ).Ratio(14),
            new Layout("footer", BuildFooterPanel()).Ratio(2)
        );

        EnsureSelectedProcess();
        UpdateAspireStatusPanel();
        UpdateProcessPanel();
        UpdateProcessDetailsPanel();
        UpdateProcessLogsPanel(forceReload: true);
        UpdateFooterPanel();
        serviceStatusState = BuildServiceStatusState();
        selectedDetailsState = BuildSelectedProcessDetailsState();

        ConsoleCancelEventHandler cancelHandler = (_, e) =>
        {
            e.Cancel = true;
            sessionCts.Cancel();
        };

        Console.CancelKeyPress += cancelHandler;

        try
        {
            // Render the live layout (with spinners) while the dashboard is still initializing
            await RenderLiveInitializationAsync();

            await AnsiConsole.Live(mainLayout)
                .Overflow(VerticalOverflow.Crop)
                .Cropping(VerticalOverflowCropping.Bottom)
                .AutoClear(false)
                .StartAsync(async ctx =>
                {
                    ctx.Refresh();

                    while (!sessionToken.IsCancellationRequested)
                    {
                        var shouldRefresh = CheckDashboardStatusChanged()
                            | CheckServiceStatusChanged()
                            | CheckConsoleSizeChanged()
                            | CheckInventoryChanged()
                            | CheckSelectedProcessLogEntries()
                            | CheckSelectedProcessDetailsChanged();

                        if (Console.KeyAvailable)
                        {
                            var pressedKey = Console.ReadKey(true);
                            var keyHandled = true;
                            switch (pressedKey.Key)
                            {
                                case ConsoleKey.UpArrow:
                                {
                                    MoveSelection(-1);
                                    break;
                                }
                                case ConsoleKey.DownArrow:
                                {
                                    MoveSelection(1);
                                    break;
                                }
                                case ConsoleKey.L:
                                {
                                    reloadSelectedProcessLogs = true;
                                    actionStatus = "Reloading selected process logs (history + live)...";
                                    UpdateFooterPanel();
                                    break;
                                }
                                case ConsoleKey.S:
                                {
                                    await StopSelectedProcessAsync();
                                    break;
                                }
                                case ConsoleKey.R:
                                {
                                    await RestartSelectedProcessAsync();
                                    break;
                                }
                                case ConsoleKey.D:
                                {
                                    await DeleteSelectedProcessAsync();
                                    break;
                                }
                                case ConsoleKey.K:
                                {
                                    killRequested = true;
                                    actionStatus = "Killing runner and all managed processes...";
                                    UpdateFooterPanel();
                                    sessionCts.Cancel();
                                    break;
                                }
                                case ConsoleKey.H or ConsoleKey.Help:
                                {
                                    if (PlatformHelper.GetUrlOpener(RunnerInfo.ProjectUrl) is { } opener)
                                    {
                                        ProcessHelper.Run(opener.Executable, opener.Arguments);
                                        actionStatus = "Opened project documentation/help.";
                                        UpdateFooterPanel();
                                    }

                                    break;
                                }
                                case ConsoleKey.B:
                                {
                                    if (_dashboard is { IsRunning: true, Url: { } url } && PlatformHelper.GetUrlOpener(url) is { } opener)
                                    {
                                        ProcessHelper.Run(opener.Executable, opener.Arguments);
                                        actionStatus = "Opened Aspire dashboard in browser.";
                                        UpdateFooterPanel();
                                    }

                                    break;
                                }
                                case ConsoleKey.C when pressedKey.Modifiers.HasFlag(ConsoleModifiers.Control):
                                case ConsoleKey.Escape:
                                {
                                    sessionCts.Cancel();
                                    break;
                                }
                                default:
                                {
                                    keyHandled = false;
                                    break;
                                }
                            }

                            shouldRefresh |= keyHandled;
                        }

                        if (shouldRefresh)
                        {
                            ctx.Refresh();
                        }

                        try
                        {
                            await Task.Delay(40, sessionToken).ConfigureAwait(false);
                        }
                        catch (OperationCanceledException)
                        {
                            break;
                        }
                    }
                }).ConfigureAwait(false);

            if (killRequested)
            {
                await KillAllManagedProcessesAsync();
                return 0;
            }

            await ShutdownManagedProcessesAsync();
            return 0;
        }
        finally
        {
            Console.CancelKeyPress -= cancelHandler;
        }

        async Task RenderLiveInitializationAsync()
        {
            var waitingPrompt = new Align(new Text("Waiting for dashboard startup"), HorizontalAlignment.Left, VerticalAlignment.Bottom);
            mainLayout["footer"].Update(new Panel(waitingPrompt)
                .Header($"[{Widgets.PrimaryColorText}]Startup[/]")
                .BorderStyle(new Style(Widgets.PrimaryColor, decoration: Decoration.Dim))
                .Expand());
            AnsiConsole.Clear();

            try
            {
                await AnsiConsole.Live(mainLayout)
                    .Overflow(VerticalOverflow.Crop)
                    .Cropping(VerticalOverflowCropping.Bottom)
                    .StartAsync(async ctx =>
                    {
                        var spinner = !AnsiConsole.Console.Profile.Capabilities.Unicode ? Spinner.Known.Ascii : Spinner.Known.Dots;
                        var frameIndex = 0;

                        while (_dashboard.IsRunning && !sessionToken.IsCancellationRequested)
                        {
                            var currentFrame = new Markup(spinner.Frames[frameIndex % spinner.Frames.Count], Widgets.PrimaryColor);
                            var currentPrompt = new Align(
                                new Columns(currentFrame, new Text("Waiting for dashboard startup")).Collapse(),
                                HorizontalAlignment.Left,
                                VerticalAlignment.Bottom
                            );

                            mainLayout["footer"].Update(new Panel(currentPrompt)
                                .Header($"[{Widgets.PrimaryColorText}]Startup[/]")
                                .BorderStyle(new Style(Widgets.PrimaryColor, decoration: Decoration.Dim))
                                .Expand());

                            UpdateTableCells(currentFrame);
                            UpdateAspireStatusPanel();
                            UpdateProcessPanel();
                            UpdateProcessDetailsPanel();
                            UpdateProcessLogsPanel(forceReload: true);
                            ctx.Refresh();

                            var grpcReady = !otlpEndpoints.Contains("grpc")
                                || (_dashboard.OtlpEndpoints?.Any(endpoint => endpoint.Protocol.Contains("grpc", StringComparison.OrdinalIgnoreCase)) is true);
                            var httpReady = !otlpEndpoints.Contains("http")
                                || (_dashboard.OtlpEndpoints?.Any(endpoint => endpoint.Protocol.Contains("http", StringComparison.OrdinalIgnoreCase)) is true);
                            var otlpReady = grpcReady && httpReady;
                            var mcpReady = dashboardOptions.Mcp.Disabled is true || _dashboard.McpEndpoint != null;

                            if (_dashboard.Url is not null && otlpReady && mcpReady)
                            {
                                break;
                            }

                            frameIndex++;

                            try
                            {
                                await Task.Delay(spinner.Interval, sessionToken).ConfigureAwait(false);
                            }
                            catch (OperationCanceledException)
                            {
                                break;
                            }
                        }
                    }).ConfigureAwait(false);
            }
            catch (OperationCanceledException)
            {
                // Startup can be canceled through Ctrl+C/Esc; treat as normal flow.
            }

            UpdateTableCells(defaultStatus);
            UpdateAspireStatusPanel();
            UpdateProcessPanel();
            UpdateProcessDetailsPanel();
            UpdateProcessLogsPanel(forceReload: true);
            actionStatus = "Runner ready. Select process and use S/R/D/L actions.";
            UpdateFooterPanel();
            serviceStatusState = BuildServiceStatusState();
            selectedDetailsState = BuildSelectedProcessDetailsState();
        }

        void UpdateTableCells(Renderable defaultContent)
        {
            if (_dashboard is null)
            {
                ResetTableCells();
                return;
            }

            var dashboardRunning = _dashboard.IsRunning;

            if (!dashboardRunning || _dashboard.Url is null)
            {
                table.UpdateCell(0, 1, defaultContent);
                table.UpdateCell(0, 2, "");
                table.UpdateCell(0, 3, "");
            }
            else
            {
                table.UpdateCell(0, 1, Widgets.TableColumn([Widgets.StatusSymbol(true)], HorizontalAlignment.Center));
                table.UpdateCell(0, 2, Widgets.TableColumn([$"[{Widgets.PrimaryColorText} link={_dashboard.Url}]{settings.DashboardPort}[/]".Widget()], HorizontalAlignment.Center));
                if (settings.UseAuth)
                {
                    var token = UrlHelper.GetQuery(_dashboard.Url)["t"].Truncate(35);
                    table.UpdateCell(0, 3, Widgets.TableColumn([$"[{Widgets.PrimaryColorText}]{token}[/]".Widget()], HorizontalAlignment.Center));
                }
            }

            if (!dashboardRunning
                || !otlpEndpoints.Contains("grpc")
                || _dashboard.OtlpEndpoints?.FirstOrDefault(e => e.Protocol.Contains("grpc", StringComparison.OrdinalIgnoreCase)) is null)
            {
                table.UpdateCell(1, 1, defaultContent);
                table.UpdateCell(1, 2, "");
                table.UpdateCell(1, 3, "");
            }
            else
            {
                table.UpdateCell(1, 1, Widgets.TableColumn([Widgets.StatusSymbol(true)], HorizontalAlignment.Center));
                table.UpdateCell(1, 2, Widgets.TableColumn([$"[{Widgets.PrimaryColorText}]{settings.OtlpPort}[/]".Widget()], HorizontalAlignment.Center));
                if (!string.IsNullOrWhiteSpace(settings.OtlpKey))
                {
                    table.UpdateCell(1, 3, Widgets.TableColumn([$"x-otlp-api-key=[{Widgets.PrimaryColorText}]{settings.OtlpKey.Truncate(18)}[/]".Widget()], HorizontalAlignment.Center));
                }
            }

            if (!dashboardRunning
                || !otlpEndpoints.Contains("http")
                || _dashboard.OtlpEndpoints?.FirstOrDefault(e => e.Protocol.Contains("http", StringComparison.OrdinalIgnoreCase)) is null)
            {
                table.UpdateCell(2, 1, defaultContent);
                table.UpdateCell(2, 2, "");
                table.UpdateCell(2, 3, "");
            }
            else
            {
                table.UpdateCell(2, 1, Widgets.TableColumn([Widgets.StatusSymbol(true)], HorizontalAlignment.Center));
                table.UpdateCell(2, 2, Widgets.TableColumn([$"[{Widgets.PrimaryColorText}]{settings.OtlpHttpPort}[/]".Widget()], HorizontalAlignment.Center));
                if (!string.IsNullOrWhiteSpace(settings.OtlpKey))
                {
                    table.UpdateCell(2, 3, Widgets.TableColumn([$"x-otlp-api-key=[{Widgets.PrimaryColorText}]{settings.OtlpKey.Truncate(18)}[/]".Widget()], HorizontalAlignment.Center));
                }
            }

            if (!dashboardRunning || dashboardOptions.Mcp.Disabled is true || _dashboard.McpEndpoint is null)
            {
                table.UpdateCell(3, 1, defaultContent);
                table.UpdateCell(3, 2, "");
                table.UpdateCell(3, 3, "");
            }
            else
            {
                table.UpdateCell(3, 1, Widgets.TableColumn([Widgets.StatusSymbol(true)], HorizontalAlignment.Center));
                table.UpdateCell(3, 2, Widgets.TableColumn([$"[{Widgets.PrimaryColorText}]{settings.McpPort}[/]".Widget()], HorizontalAlignment.Center));
                if (!string.IsNullOrWhiteSpace(settings.McpKey))
                {
                    table.UpdateCell(3, 3, Widgets.TableColumn([$"x-mcp-api-key=[{Widgets.PrimaryColorText}]{settings.McpKey.Truncate(18)}[/]".Widget()], HorizontalAlignment.Center));
                }
            }
        }

        void ResetTableCells()
        {
            table.UpdateCell(0, 1, defaultStatus);
            table.UpdateCell(0, 2, "");
            table.UpdateCell(0, 3, "");
            table.UpdateCell(1, 1, defaultStatus);
            table.UpdateCell(1, 2, "");
            table.UpdateCell(1, 3, "");
            table.UpdateCell(2, 1, defaultStatus);
            table.UpdateCell(2, 2, "");
            table.UpdateCell(2, 3, "");
            table.UpdateCell(3, 1, defaultStatus);
            table.UpdateCell(3, 2, "");
            table.UpdateCell(3, 3, "");
        }

        bool CheckDashboardStatusChanged()
        {
            var dashboardRunning = _dashboard.IsRunning;
            if (dashboardRunning == _dashboardStarted)
            {
                // status is unchanged
                return false;
            }

            if (dashboardRunning)
            {
                _dashboardStarted = true;
                UpdateTableCells(defaultStatus);
            }
            else
            {
                _dashboardStarted = false;
                ResetTableCells();
            }

            SyncDashboardInventory();

            return true;
        }

        bool CheckConsoleSizeChanged()
        {
            if (AnsiConsole.Profile.Width == _currentWidth && AnsiConsole.Profile.Height == _currentHeight)
            {
                return false;
            }

            _currentWidth = AnsiConsole.Profile.Width;
            _currentHeight = AnsiConsole.Profile.Height;

            mainLayout["header"].Update(BuildHeader()).Ratio(1);
            UpdateTableCells(defaultStatus);
            UpdateAspireStatusPanel();
            UpdateProcessPanel();
            UpdateProcessDetailsPanel();
            UpdateProcessLogsPanel(forceReload: true);
            UpdateFooterPanel();
            serviceStatusState = BuildServiceStatusState();
            selectedDetailsState = BuildSelectedProcessDetailsState();

            return true;
        }

        bool CheckInventoryChanged()
        {
            SyncDashboardInventory();

            var snapshot = BuildInventoryState();
            if (snapshot == _inventoryState)
            {
                return false;
            }

            EnsureSelectedProcess();
            UpdateProcessPanel();
            UpdateProcessDetailsPanel();
            reloadSelectedProcessLogs = true;
            return true;
        }

        bool CheckServiceStatusChanged()
        {
            var snapshot = BuildServiceStatusState();
            if (snapshot == serviceStatusState)
            {
                return false;
            }

            serviceStatusState = snapshot;
            UpdateTableCells(defaultStatus);
            UpdateAspireStatusPanel();
            SyncDashboardInventory();
            return true;
        }

        void SyncDashboardInventory()
        {
            if (_dashboard is null)
            {
                return;
            }

            var dashboardExe = DotnetCli.Executable;
            var dashboardArgs = $"exec {Path.Combine(_dashboard.InstallationPath, Dashboard.DllName)}";
            var dashboardEnvironment = dashboardOptions.ToEnvironmentVariables();
            var command = $"{RunnerInfo.CommandName} aspire run {settings.Version}".TrimEnd();
            var details = BuildDashboardDetails();
            var dashboardPorts = GetDashboardPorts();

            if (string.IsNullOrWhiteSpace(_dashboardProcessId))
            {
                var processEntry = _processManager.Register(
                    _dashboard,
                    ProcessProfile.AspireDashboard,
                    command,
                    details,
                    preferredId: "aspire-dashboard",
                    executable: dashboardExe,
                    arguments: dashboardArgs,
                    environmentVariables: BuildEnvironmentString(dashboardEnvironment),
                    workingDirectory: _dashboard.InstallationPath,
                    exposedPorts: dashboardPorts);
                _dashboardProcessId = processEntry.Id;
                return;
            }

            _processManager.UpdateMetadata(
                _dashboardProcessId,
                command,
                details,
                executable: dashboardExe,
                arguments: dashboardArgs,
                environmentVariables: BuildEnvironmentString(dashboardEnvironment),
                workingDirectory: _dashboard.InstallationPath,
                exposedPorts: dashboardPorts);
        }

        Table BuildInventoryTable()
        {
            var inventory = new Table()
                .Collapse()
                .BorderStyle(new Style(Widgets.PrimaryColor, decoration: Decoration.Dim))
                .AddColumn("", c => c.Centered().NoWrap().Width(3))
                .AddColumn("Id", c => c.NoWrap().Width(16))
                .AddColumn("Process", c => c.NoWrap().Width(24))
                .AddColumn("Status", c => c.Centered().NoWrap().Width(8))
                .AddColumn("PID", c => c.Centered().NoWrap().Width(8))
                .AddColumn("Ports", c => c.Centered().NoWrap().Width(18))
                .AddColumn("Profile", c => c.Centered().NoWrap().Width(12));

            var entries = _processManager.List();
            if (entries.Count == 0)
            {
                inventory.AddRow(
                    "".Widget(),
                    "-".Widget(),
                    "No managed processes".Widget(),
                    "".Widget(),
                    "".Widget(),
                    "".Widget(),
                    "".Widget());
                return inventory;
            }

            foreach (var entry in entries)
            {
                var running = entry.Process.IsRunning;
                var profileText = entry.Profile switch
                {
                    ProcessProfile.AspireDashboard => "Aspire",
                    ProcessProfile.ExecutableProcess => "Executable",
                    _ => entry.Profile.ToString()
                };

                var selected = selectedProcessId.Equals(entry.Id, StringComparison.OrdinalIgnoreCase);
                var selector = selected ? $"[{Widgets.PrimaryColorText}]>[/]" : " ";

                inventory.AddRow(
                    selector.Widget(),
                    entry.Id.Truncate(16).Widget(),
                    entry.Process.DisplayName.Truncate(24).Widget(),
