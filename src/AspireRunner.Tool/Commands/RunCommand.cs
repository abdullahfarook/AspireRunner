        bool UpdateSelectedProcessLogs(bool forceReload)
        {
            EnsureSelectedProcess();
            var selected = GetSelectedProcessEntry();

            if (selected is null)
            {
                if (processLogEntries.Count == 0 && string.IsNullOrWhiteSpace(processLogsProcessId))
                {
                    return false;
                }

                processLogsProcessId = string.Empty;
                processLogEntries.Clear();
                return true;
            }

            var changed = false;

            if (forceReload || !processLogsProcessId.Equals(selected.Id, StringComparison.OrdinalIgnoreCase))
            {
                processLogsProcessId = selected.Id;
                processLogEntries.Clear();
                processLogCursors[selected.Id] = (0, 0);
                changed = true;
            }

            if (selected.Process is not IProcessOutputSource outputSource)
            {
                var unsupportedMessage = "Selected process does not expose output streams.";
                if (processLogEntries.Count != 1 || !processLogEntries[0].Message.Equals(unsupportedMessage, StringComparison.Ordinal))
                {
                    processLogEntries.Clear();
                    processLogEntries.Add(("info", unsupportedMessage));
                    return true;
                }

                return changed;
            }

            if (!processLogCursors.TryGetValue(selected.Id, out var cursor))
            {
                cursor = (0, 0);
            }

            var stdoutSnapshot = outputSource.GetStdoutSnapshot();
            var stderrSnapshot = outputSource.GetStderrSnapshot();

            if (stdoutSnapshot.Count < cursor.StdoutCount || stderrSnapshot.Count < cursor.StderrCount)
            {
                processLogEntries.Clear();
                cursor = (0, 0);
                changed = true;
            }

            for (var i = cursor.StdoutCount; i < stdoutSnapshot.Count; i++)
            {
                AppendProcessLog("stdout", stdoutSnapshot[i]);
                changed = true;
            }

            for (var i = cursor.StderrCount; i < stderrSnapshot.Count; i++)
            {
                AppendProcessLog("stderr", stderrSnapshot[i]);
                changed = true;
            }

            processLogCursors[selected.Id] = (stdoutSnapshot.Count, stderrSnapshot.Count);
            return changed;
        }

        void AppendProcessLog(string stream, string line)
        {
            if (string.IsNullOrWhiteSpace(line))
            {
                return;
            }

            processLogEntries.Add((stream, line));
            if (processLogEntries.Count > maxProcessLogLines)
            {
                processLogEntries.RemoveRange(0, processLogEntries.Count - maxProcessLogLines);
            }
        }

        static string ResolveProcessLogColor(string stream, string message)
        {
            var text = message.TrimStart();

            if (text.StartsWith("warn", StringComparison.OrdinalIgnoreCase)
                || text.StartsWith("warning", StringComparison.OrdinalIgnoreCase))
            {
                return "yellow";
            }

            if (text.StartsWith("error", StringComparison.OrdinalIgnoreCase)
                || text.StartsWith("err", StringComparison.OrdinalIgnoreCase)
                || text.StartsWith("fail", StringComparison.OrdinalIgnoreCase)
                || text.StartsWith("fatal", StringComparison.OrdinalIgnoreCase)
                || text.StartsWith("crit", StringComparison.OrdinalIgnoreCase))
            {
                return "red";
            }

            if (text.StartsWith("info", StringComparison.OrdinalIgnoreCase)
                || text.StartsWith("information", StringComparison.OrdinalIgnoreCase)
                || text.StartsWith("debug", StringComparison.OrdinalIgnoreCase)
                || text.StartsWith("trace", StringComparison.OrdinalIgnoreCase))
            {
                return "white";
            }

            return stream.Equals("stderr", StringComparison.OrdinalIgnoreCase) ? "red" : "white";
        }

